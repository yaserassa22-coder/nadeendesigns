import fs from "fs";

const root = "C:/Users/malma/Desktop/nadeendesigns";
const read = (p) => fs.readFileSync(`${root}/${p}`, "utf8");
const write = (p, s) => {
  fs.writeFileSync(`${root}/${p}`, s);
  console.log("wrote", p);
};
const patch = (rel, fn) => {
  let s = read(rel).replace(/\r\n/g, "\n");
  const n = fn(s);
  if (n !== s) {
    write(rel, n);
  } else console.log("unchanged", rel);
};

function injectBefore(dict, marker, block, label) {
  if (dict.includes(block.slice(0, 50).trim())) {
    console.log("skip", label);
    return dict;
  }
  const idx = dict.indexOf(marker);
  if (idx < 0) {
    console.warn("MISS", label, marker.slice(0, 60));
    return dict;
  }
  return dict.slice(0, idx) + block + dict.slice(idx);
}

